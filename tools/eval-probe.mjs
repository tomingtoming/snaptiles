// node tools/eval-probe.mjs <file> <key:ms> <jsExpr> — evaluates an expression in page after holding a key
import { chromium } from 'playwright';
import { readFileSync } from 'node:fs';
const [file, spec, expr] = process.argv.slice(2);
const buf = readFileSync(file);
let text = new TextDecoder('utf-8', { fatal: false }).decode(buf);
if (/�/.test(text)) text = new TextDecoder('shift_jis').decode(buf);
const browser = await chromium.launch({ args: ['--use-gl=angle', '--use-angle=swiftshader', '--enable-unsafe-swiftshader'] });
const page = await browser.newPage();
await page.goto('http://127.0.0.1:5173/', { waitUntil: 'networkidle' });
await page.fill('#source', text);
await page.click('#run');
await page.waitForTimeout(6500);
const [code, ms = '800'] = spec.split(':');
await page.focus('#view');
await page.keyboard.down(code);
await page.waitForTimeout(Number(ms));
console.log(JSON.stringify(await page.evaluate(expr)));
await page.keyboard.up(code);
await browser.close();
